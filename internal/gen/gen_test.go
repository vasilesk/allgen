const colorSource = `package colors

//go:generate allgen
const (
	Red Color = iota
	Green
)

type Color int
`

func TestGenerateDefaults(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"color.go": colorSource})

	require.NoError(t, gen.Generate(t.Context(), params(dir, "color.go", 3)))

	assert.Equal(t, `// Code generated by allgen; DO NOT EDIT.
// Source: color.go
// Directive: //go:generate allgen

package colors

// AllColors returns the constants of the block in color.go in declaration order.
// Each call returns a new slice.
func AllColors() []Color {
	return []Color{
		Red,
		Green,
	}
}
`, readFile(t, dir, "all_colors_gen.go"))

	assert.Equal(t, `// Code generated by allgen; DO NOT EDIT.
// Source: color.go
// Directive: //go:generate allgen

package colors

import (
	"testing"

	"github.com/vasilesk/allgen"
)

func TestAllColorsUpToDate(t *testing.T) {
	t.Parallel()

	allgen.Check(t, allgen.Block{
		File:      "color.go",
		Directive: "//go:generate allgen",
		Names: []string{
			"Red",
			"Green",
		},
	})
}
`, readFile(t, dir, "all_colors_gen_test.go"))
}

func TestGenerateOptions(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"timeouts.go": `//go:build !windows

package timeouts

import "time"

//go:generate allgen -name timeouts
var (
	Short = time.Second
	Long  = time.Minute
)
`})

	p := params(dir, "timeouts.go", 7)
	p.Name = mo.Some(gen.FuncName("timeouts"))
	p.Output = mo.Some(gen.FileName("timeouts_list.go"))
	p.Test = false

	require.NoError(t, gen.Generate(t.Context(), p))

	assert.Equal(t, `// Code generated by allgen; DO NOT EDIT.
// Source: timeouts.go
// Directive: //go:generate allgen -name timeouts

//go:build !windows

package timeouts

import (
	"time"
)

// timeouts returns the variables of the block in timeouts.go in declaration order.
// Each call returns a new slice.
func timeouts() []time.Duration {
	return []time.Duration{
		Short,
		Long,
	}
}
`, readFile(t, dir, "timeouts_list.go"))
	assert.NoFileExists(t, filepath.Join(dir, "timeouts_list_test.go"))
}

func TestGenerateUnexportedType(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"status.go": `package p

//go:generate allgen
const (
	active status = "active"
)

type status string
`})

	require.NoError(t, gen.Generate(t.Context(), params(dir, "status.go", 3)))
	assert.Contains(t, readFile(t, dir, "all_statuses_gen.go"), "func allStatuses() []status {")
	assert.Contains(t, readFile(t, dir, "all_statuses_gen_test.go"), "func TestAllStatusesUpToDate(")
}

func TestGenerateAfterMemberRemoved(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"color.go": colorSource})
	require.NoError(t, gen.Generate(t.Context(), params(dir, "color.go", 3)))

	writeFiles(t, dir, map[string]string{"color.go": strings.Replace(colorSource, "\tGreen\n", "", 1)})

	require.NoError(t, gen.Generate(t.Context(), params(dir, "color.go", 3)),
		"the stale list referring to Green must not break type checking")
	assert.NotContains(t, readFile(t, dir, "all_colors_gen.go"), "Green")
}

func TestGenerateAfterDirectiveChanged(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"color.go": colorSource})
	require.NoError(t, gen.Generate(t.Context(), params(dir, "color.go", 3)))

	writeFiles(t, dir, map[string]string{"color.go": strings.Replace(colorSource, "allgen", "allgen -test", 1)})

	require.NoError(t, gen.Generate(t.Context(), params(dir, "color.go", 3)),
		"files of a directive that is gone may be replaced")
	assert.Contains(t, readFile(t, dir, "all_colors_gen.go"), "// Directive: //go:generate allgen -test\n")
}

func TestGenerateErrors(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name    string
		files   map[string]string
		file    string
		line    int
		wantErr error
	}{
		{
			name: "basic type without name",
			files: map[string]string{"errs.go": `package p

import "errors"

//go:generate allgen
var ErrA = errors.New("a")
`},
			file:    "errs.go",
			line:    5,
			wantErr: gen.ErrNameRequired,
		},
		{
			name: "type from another package without name",
			files: map[string]string{"t.go": `package p

import "time"

//go:generate allgen
const A time.Duration = 1
`},
			file:    "t.go",
			line:    5,
			wantErr: gen.ErrNameRequired,
		},
		{
			name:    "pointer type without name",
			files:   map[string]string{"t.go": "package p\n\n//go:generate allgen\nvar A = &T{}\n\ntype T struct{}\n"},
			file:    "t.go",
			line:    3,
			wantErr: gen.ErrNameRequired,
		},
		{
			name: "mixed types",
			files: map[string]string{"t.go": `package p

//go:generate allgen
const (
	A T = 1
	B U = 2
)

type (
	T int
	U int
)
`},
			file:    "t.go",
			line:    3,
			wantErr: gen.ErrMixedTypes,
		},
		{
			name:    "untyped constant",
			files:   map[string]string{"t.go": "package p\n\n//go:generate allgen\nconst A = 1\n"},
			file:    "t.go",
			line:    3,
			wantErr: gen.ErrUntyped,
		},
		{
			name:    "undefined type",
			files:   map[string]string{"t.go": "package p\n\n//go:generate allgen\nconst A Missing = 1\n"},
			file:    "t.go",
			line:    3,
			wantErr: gen.ErrNotTypeChecked,
		},
		{
			name:    "function name declared by hand",
			files:   map[string]string{"color.go": colorSource, "all.go": "package colors\n\nfunc AllColors() {}\n"},
			file:    "color.go",
			line:    3,
			wantErr: gen.ErrNameTaken,
		},
		{
			name:    "output file written by hand",
			files:   map[string]string{"color.go": colorSource, "all_colors_gen.go": "package colors\n"},
			file:    "color.go",
			line:    3,
			wantErr: gen.ErrForeignFile,
		},
		{
			name: "output file of another block",
			files: map[string]string{
				"color.go": colorSource,
				"more.go":  "package colors\n\n//go:generate allgen -x\nconst Blue Color = 3\n",
				"all_colors_gen.go": "// Code generated by allgen; DO NOT EDIT.\n// Source: more.go\n" +
					"// Directive: //go:generate allgen -x\n\npackage colors\n",
			},
			file:    "color.go",
			line:    3,
			wantErr: gen.ErrOutputTaken,
		},
		{
			name:    "file excluded by build constraints",
			files:   map[string]string{"color.go": "//go:build never\n\n" + colorSource},
			file:    "color.go",
			line:    5,
			wantErr: gen.ErrExcluded,
		},
		{
			name:    "test file",
			files:   map[string]string{"color_test.go": colorSource},
			file:    "color_test.go",
			line:    3,
			wantErr: gen.ErrTestFile,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, tt.files)

			err := gen.Generate(t.Context(), params(dir, tt.file, tt.line))
			require.ErrorIs(t, err, tt.wantErr)
			assert.NoFileExists(t, filepath.Join(dir, "all_colors_gen_test.go"), "nothing is written on failure")
		})
	}
}

func params(dir, file string, line int) gen.Params {
	return gen.Params{
		Dir:    dir,
		File:   file,
		Line:   line,
		Name:   mo.None[gen.FuncName](),
		Output: mo.None[gen.FileName](),
		Test:   true,
	}
}

func writeModule(t *testing.T, files map[string]string) string {
	t.Helper()

	dir, err := filepath.EvalSymlinks(t.TempDir())
	require.NoError(t, err)

	writeFiles(t, dir, map[string]string{"go.mod": "module example.com/m\n\ngo 1.26\n"})
	writeFiles(t, dir, files)

	return dir
}

func writeFiles(t *testing.T, dir string, files map[string]string) {
	t.Helper()

	for name, content := range files {
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600))
	}
}

func readFile(t *testing.T, dir, name string) string {
	t.Helper()

	content, err := os.ReadFile(filepath.Join(dir, name))
	require.NoError(t, err)

	return string(content)
}
