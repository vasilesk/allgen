package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"text/template"

	"github.com/samber/mo"
)

// output is a rendered file ready to be written to the package directory.
type output struct {
	name    string
	content []byte
}

// renderFiles renders the function file and, when withTest is set, its test.
func renderFiles(l list, maybeOutput mo.Option[FileName], withTest bool) ([]output, error) {
	name, err := outputName(maybeOutput, l.Func)
	if err != nil {
		return nil, err
	}

	targets := []target{{name: string(name), text: listTemplate}}
	if withTest {
		targets = append(targets, target{name: name.TestFile(), text: testTemplate})
	}

	files := make([]output, 0, len(targets))

	for _, t := range targets {
		content, err := render(t.text, l)
		if err != nil {
			return nil, fmt.Errorf("rendering %s: %w", t.name, err)
		}

		files = append(files, output{name: t.name, content: content})
	}

	return files, nil
}

// target is a file to render: its name and the template of its body.
type target struct {
	name string
	text string
}

func outputName(maybeOutput mo.Option[FileName], fn FuncName) (FileName, error) {
	if name, ok := maybeOutput.Get(); ok {
		return name, nil
	}

	return defaultFileName(fn)
}

func render(text string, l list) ([]byte, error) {
	tmpl, err := template.New("").Parse(headerTemplate + text)
	if err != nil {
		return nil, fmt.Errorf("parsing template: %w", err)
	}

	var buf bytes.Buffer

	err = tmpl.Execute(&buf, l)
	if err != nil {
		return nil, fmt.Errorf("executing template: %w", err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting source: %w", err)
	}

	return formatted, nil
}

// generatedLine opens every file written by allgen. It follows the convention recognized
// by Go tools for generated files.
const generatedLine = "// Code generated by allgen; DO NOT EDIT."

// The header identifies the block a file was generated for by the source file name and
// the directive text, the same pair the check uses, so that a later run can tell its own
// files from those of other blocks.
const (
	sourcePrefix    = "// Source: "
	directivePrefix = "// Directive: "
	headerTemplate  = generatedLine + "\n" +
		sourcePrefix + "{{.Source}}\n" +
		directivePrefix + "{{.Directive}}\n" + `
{{with .BuildConstraint.OrEmpty}}{{.}}

{{end}}package {{.Package}}
`
)

const listTemplate = `
{{with .Type.Imports}}import (
{{range .}}	{{.}}
{{end}})
{{end}}
// {{.Func}} returns the {{.Members}} of the block in {{.Source}} in declaration order.
// Each call returns a new slice.
func {{.Func}}() []{{.Type.Expr}} {
	return []{{.Type.Expr}}{
{{range .Names}}		{{.}},
{{end}}	}
}
`

const testTemplate = `
import (
	"testing"

	"github.com/vasilesk/allgen"
)

func {{.TestName}}(t *testing.T) {
	t.Parallel()

	allgen.Check(t, allgen.Block{
		File:      {{printf "%q" .Source}},
		Directive: {{printf "%q" .Directive}},
		Names: []string{
{{range .Names}}			{{printf "%q" .}},
{{end}}		},
	})
}
`
