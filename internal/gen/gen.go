// Package gen writes the function returning the members of a const or var block, and the
// test that fails once the function no longer matches the block.
package gen

import (
	"context"
	"errors"
	"fmt"
	"go/token"
	"go/types"
	"path/filepath"
	"strings"

	"github.com/samber/mo"
	"golang.org/x/tools/go/packages"

	"github.com/vasilesk/allgen/internal/source"
)

// Params configures one run of [Generate].
type Params struct {
	// Dir is the absolute path of the package directory.
	Dir string
	// File is the name of the file in Dir holding the directive.
	File string
	// Line is the 1-based line of the directive in File.
	Line int
	// Name is the name of the generated function. When absent, it is derived from the
	// type of the members: All<Type>s, or all<Type>s for an unexported type.
	Name mo.Option[FuncName]
	// Output is the name of the generated file. When absent, it is the function name in
	// snake_case with the _gen.go suffix.
	Output mo.Option[FileName]
	// Test enables the test checking that the function is up to date. Its file name is
	// the output name with the _test.go suffix.
	Test bool
}

// Generate writes the function returning the members of the block below the directive
// at p.Line of p.File, and its test when p.Test is set.
//
// Files previously generated for the same directive are replaced. A file not generated
// by allgen, or generated for a directive still present in the package, is never
// overwritten: Generate fails instead, before writing anything.
func Generate(ctx context.Context, p Params) error {
	if strings.HasSuffix(p.File, "_test.go") {
		return fmt.Errorf("%w: %s", ErrTestFile, p.File)
	}

	src, err := readSource(p.Dir, p.File, p.Line)
	if err != nil {
		return fmt.Errorf("reading block: %w", err)
	}

	pkg, err := load(ctx, p.Dir, p.File, src.file.Package())
	if err != nil {
		return fmt.Errorf("loading package: %w", err)
	}

	l, err := newList(pkg, src, p.Name)
	if err != nil {
		return fmt.Errorf("resolving list: %w", err)
	}

	files, err := renderFiles(l, p.Output, p.Test)
	if err != nil {
		return fmt.Errorf("rendering files: %w", err)
	}

	return writeFiles(p.Dir, files, l.owner())
}

var (
	// ErrTestFile means a directive is placed in a _test.go file, which is not supported.
	ErrTestFile = errors.New("blocks in test files are not supported")
	// ErrNameRequired means the type of the members gives no default function name: it is
	// not a non-generic named type declared in the package of the block.
	ErrNameRequired = errors.New("function name required")
	// ErrNameTaken means the function name is already declared in the package by a file
	// other than one generated by allgen.
	ErrNameTaken = errors.New("function name already declared in package")
)

// directiveBlock is a block together with the directive placed above it.
type directiveBlock struct {
	file      source.File
	fileName  string
	directive string
	block     source.Block
}

// readSource finds the directive at line of file and the block below it. The directive
// text must be unique in the file, as the generated files and the check identify the
// block by it.
func readSource(dir, fileName string, line int) (directiveBlock, error) {
	file, err := source.Parse(filepath.Join(dir, fileName))
	if err != nil {
		return directiveBlock{}, fmt.Errorf("parsing source: %w", err)
	}

	directive, err := file.DirectiveAt(line)
	if err != nil {
		return directiveBlock{}, fmt.Errorf("reading directive: %w", err)
	}

	_, err = file.DirectiveLine(directive)
	if err != nil {
		return directiveBlock{}, fmt.Errorf("checking directive: %w", err)
	}

	block, err := file.Block(line)
	if err != nil {
		return directiveBlock{}, fmt.Errorf("finding block: %w", err)
	}

	return directiveBlock{file: file, fileName: fileName, directive: directive, block: block}, nil
}

// list is everything the generated files are rendered from.
type list struct {
	Package         string
	BuildConstraint mo.Option[string]
	Source          string
	Directive       string
	Kind            token.Token
	Func            FuncName
	Type            typeRef
	Names           []string
}

func newList(pkg *packages.Package, src directiveBlock, maybeName mo.Option[FuncName]) (list, error) {
	elem, err := elementType(pkg, src.block.Names)
	if err != nil {
		return list{}, err
	}

	name, err := funcName(maybeName, elem, pkg.Types)
	if err != nil {
		return list{}, err
	}

	if obj := pkg.Types.Scope().Lookup(string(name)); obj != nil {
		return list{}, fmt.Errorf("%w: %s at %s", ErrNameTaken, name, pkg.Fset.Position(obj.Pos()))
	}

	ref, err := newTypeRef(elem, pkg.Types)
	if err != nil {
		return list{}, err
	}

	return list{
		Package:         src.file.Package(),
		BuildConstraint: mo.TupleToOption(src.file.BuildConstraint()),
		Source:          src.fileName,
		Directive:       src.directive,
		Kind:            src.block.Kind,
		Func:            name,
		Type:            ref,
		Names:           src.block.Names,
	}, nil
}

// Members names what the block declares, in plural.
func (l list) Members() string {
	if l.Kind == token.CONST {
		return "constants"
	}

	return "variables"
}

// TestName is the name of the generated test function.
func (l list) TestName() string {
	return "Test" + upperFirst(string(l.Func)) + "UpToDate"
}

func (l list) owner() owner {
	return owner{source: l.Source, directive: l.Directive}
}

func funcName(maybeName mo.Option[FuncName], elem types.Type, pkg *types.Package) (FuncName, error) {
	if name, ok := maybeName.Get(); ok {
		return name, nil
	}

	return defaultFuncName(elem, pkg)
}
