var (
	// ErrExcluded means build constraints exclude the source file from the loaded package.
	ErrExcluded = errors.New("file excluded by build constraints")
	// ErrNotTypeChecked means the type of a member could not be determined.
	ErrNotTypeChecked = errors.New("member type unknown")
	// ErrUntyped means a member is an untyped constant, so the list has no element type.
	ErrUntyped = errors.New("untyped constant")
	// ErrMixedTypes means the members of a block are not all of the same type.
	ErrMixedTypes = errors.New("members are of different types")
	// ErrImportClash means the element type refers to two packages with the same name.
	ErrImportClash = errors.New("element type refers to packages with the same name")
)

const loadMode = packages.NeedName | packages.NeedFiles | packages.NeedImports |
	packages.NeedTypes | packages.NeedSyntax | packages.NeedTypesInfo

// load type-checks the package in dir from source. Files previously generated by allgen
// are hidden, so a list left stale by a removed member does not affect the result.
// Type errors elsewhere in the package are kept in the result rather than failing the
// load: members can usually be typed regardless.
func load(ctx context.Context, dir, file, pkgName string) (*packages.Package, error) {
	overlay, err := hideGenerated(dir, pkgName)
	if err != nil {
		return nil, err
	}

	//nolint:exhaustruct_v5 // zero values of the other fields are the documented defaults
	cfg := &packages.Config{Context: ctx, Mode: loadMode, Dir: dir, Overlay: overlay}

	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		return nil, fmt.Errorf("running go list: %w", err)
	}

	if len(pkgs) != 1 {
		return nil, fmt.Errorf("expected one package in %s, got %d", dir, len(pkgs))
	}

	pkg := pkgs[0]
	if !lo.ContainsBy(pkg.GoFiles, func(f string) bool { return filepath.Base(f) == file }) {
		return nil, fmt.Errorf("%w: %s; set build tags with GOFLAGS=-tags=<tags>", ErrExcluded, file)
	}

	return pkg, nil
}

// member is an identifier of a block with its type.
type member struct {
	name string
	typ  types.Type
}

// elementType returns the type shared by the package-level identifiers with the given
// names, failing when they have different types or any of them cannot be typed.
func elementType(pkg *packages.Package, names []string) (types.Type, error) {
	members := make([]member, 0, len(names))

	for _, name := range names {
		m, err := lookupMember(pkg, name)
		if err != nil {
			return nil, err
		}

		members = append(members, m)
	}

	first := members[0]

	odd := lo.Filter(members, func(m member, _ int) bool { return !types.Identical(m.typ, first.typ) })
	if len(odd) > 0 {
		return nil, fmt.Errorf("%w: %s is %s, %s is %s", ErrMixedTypes,
			first.name, typeString(first.typ, pkg.Types), odd[0].name, typeString(odd[0].typ, pkg.Types))
	}

	return first.typ, nil
}

func lookupMember(pkg *packages.Package, name string) (member, error) {
	obj := pkg.Types.Scope().Lookup(name)
	if obj == nil || isInvalid(obj.Type()) {
		return member{}, notTypeChecked(pkg, name)
	}

	if basic, ok := obj.Type().(*types.Basic); ok && basic.Info()&types.IsUntyped != 0 {
		return member{}, fmt.Errorf("%w: %s; declare it with a type", ErrUntyped, name)
	}

	return member{name: name, typ: obj.Type()}, nil
}

func isInvalid(typ types.Type) bool {
	basic, ok := typ.(*types.Basic)

	return ok && basic.Kind() == types.Invalid
}

func notTypeChecked(pkg *packages.Package, name string) error {
	// the go command reports compile errors again as one list error; the parser and the
	// type checker locate each of them
	located := lo.Filter(pkg.Errors, func(e packages.Error, _ int) bool { return e.Kind != packages.ListError })
	if len(located) == 0 {
		located = pkg.Errors
	}

	if len(located) == 0 {
		return fmt.Errorf("%w: %s", ErrNotTypeChecked, name)
	}

	causes := lo.Map(located, func(e packages.Error, _ int) error { return e })

	return fmt.Errorf("%w: %s: %w", ErrNotTypeChecked, name, errors.Join(causes...))
}

// typeRef is a type as written in the generated file, with the imports it needs.
type typeRef struct {
	Expr    string
	Imports []importSpec
}

func newTypeRef(typ types.Type, pkg *types.Package) (typeRef, error) {
	imported := map[string]string{}
	expr := types.TypeString(typ, func(other *types.Package) string {
		if other.Path() == pkg.Path() {
			return ""
		}

		imported[other.Path()] = other.Name()

		return other.Name()
	})

	specs := lo.MapToSlice(imported, func(path, name string) importSpec { return importSpec{Name: name, Path: path} })
	slices.SortFunc(specs, func(a, b importSpec) int { return strings.Compare(a.Path, b.Path) })

	if clashes := lo.FindDuplicatesBy(specs, func(s importSpec) string { return s.Name }); len(clashes) > 0 {
		return typeRef{}, fmt.Errorf("%w: %s", ErrImportClash, clashes[0].Name)
	}

	return typeRef{Expr: expr, Imports: specs}, nil
}

// importSpec is an import of the generated file.
type importSpec struct {
	Name string
	Path string
}

// String renders the import as written in an import declaration, with the name only
// when it differs from the last element of the path.
func (s importSpec) String() string {
	if path.Base(s.Path) == s.Name {
		return strconv.Quote(s.Path)
	}

	return s.Name + " " + strconv.Quote(s.Path)
}

func typeString(typ types.Type, pkg *types.Package) string {
	return types.TypeString(typ, types.RelativeTo(pkg))
}
